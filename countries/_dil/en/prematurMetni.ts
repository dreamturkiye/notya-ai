/** An object's every sentence, put through `f` (the structure stays). */
function yapraklari<T>(x: T, f: (s: string) => string): T {
  if (typeof x === 'string') return f(x) as unknown as T
  if (x && typeof x === 'object') return Object.fromEntries(Object.entries(x as Record<string, unknown>).map(([k, v]) => [k, yapraklari(v, f)])) as T
  return x
}

