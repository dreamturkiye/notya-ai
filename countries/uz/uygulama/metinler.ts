/** The three forms an account of this country can choose. Same list as the pack's `uygulamaDilleri`. */
export const UZ_UYGULAMA_DILLERI = ['uz-Latn', 'uz-Cyrl', 'ru'] as const
export type UzUygulamaDili = (typeof UZ_UYGULAMA_DILLERI)[number]

export const UZ_UYGULAMA_METINLERI: Readonly<Record<UzUygulamaDili, UygulamaMetni>> = {
  'uz-Latn': UZ_LATN,
  'uz-Cyrl': UZ_CYRL,
  ru: RU,
}

/** Narrowing for a value that came from the server or the address bar. Anything else is Uzbek in Latin script. */
export function uzUygulamaDili(ham: unknown): UzUygulamaDili {
  return (UZ_UYGULAMA_DILLERI as readonly unknown[]).includes(ham) ? (ham as UzUygulamaDili) : 'uz-Latn'
}

export function uygulamaMetni(dil: unknown): UygulamaMetni {
  return UZ_UYGULAMA_METINLERI[uzUygulamaDili(dil)]
}

/** The form a catalogue is written in — for the few things a screen shows that are not sentences of the catalogue (a role's name, the assistant's name). */
export function metninDili(m: UygulamaMetni): UzUygulamaDili {
  return UZ_UYGULAMA_DILLERI.find((d) => UZ_UYGULAMA_METINLERI[d] === m) ?? 'uz-Latn'
}

/** Language and script as two questions: 'uz' + 'Latn' | 'Cyrl', or 'ru'. */
export type TemelDil = 'uz' | 'ru'
export type Yazi = 'Latn' | 'Cyrl'
export const temelDil = (dil: UzUygulamaDili): TemelDil => (dil === 'ru' ? 'ru' : 'uz')
export const yaziSec = (dil: UzUygulamaDili): Yazi => (dil === 'uz-Cyrl' ? 'Cyrl' : 'Latn')
export const dilBirlestir = (temel: TemelDil, yazi: Yazi): UzUygulamaDili => (temel === 'ru' ? 'ru' : yazi === 'Cyrl' ? 'uz-Cyrl' : 'uz-Latn')
