function normalizeKey(key: string): string {
  return key
    .toLowerCase()
    .trim()
    .replace(/ı/g, 'i')
    .replace(/ö/g, 'o')
    .replace(/ü/g, 'u')
    .replace(/ş/g, 's')
    .replace(/ç/g, 'c')
    .replace(/ğ/g, 'g')
    .replace(/\s+/g, '-')
    .replace(/_/g, '-')
    .replace(/&/g, '-')
}

