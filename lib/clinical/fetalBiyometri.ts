export const BIYOMETRI_ETIKET: Record<BiyometriParametre, string> = { hc: 'Baş çevresi (HC)', bpd: 'Biparietal çap (BPD)', ac: 'Karın çevresi (AC)', fl: 'Femur uzunluğu (FL)' }

function normalCdf(z: number): number { // Abramowitz-Stegun 7.1.26
  const t = 1 / (1 + 0.2316419 * Math.abs(z))
  const d = 0.3989423 * Math.exp(-z * z / 2)
  const p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.781478 + t * (-1.821256 + t * 1.330274))))
  return z > 0 ? 1 - p : p
}

/** Tam haftalar arasında doğrusal ara değer; 14-40 hafta dışı → null. */
function satir(param: BiyometriParametre, haftaOndalik: number): number[] | null {
  const t = TABLO[param]
  if (haftaOndalik < 14 || haftaOndalik > 40) return null
  const alt = Math.floor(haftaOndalik), ust = Math.min(40, alt + 1), f = haftaOndalik - alt
  const a = t[alt], b = t[ust]
  if (!a || !b) return null
  return a.map((v, i) => v + (b[i] - v) * f)
}

export interface BiyometriSonuc { parametre: BiyometriParametre; deger: number; p50: number; persentil: number; z: number; durum: 'dusuk' | 'normal' | 'yuksek' }

/** Tablodaki 7 persentil kolonu arasında z-ölçeğinde doğrusal ara değer → persentil. */
export function biyometriPersentil(param: BiyometriParametre, degerMm: number, haftaOndalik: number): BiyometriSonuc | null {
  const s = satir(param, haftaOndalik)
  if (!s || !isFinite(degerMm) || degerMm <= 0) return null
  let z: number
  if (degerMm <= s[0]) z = Z_KOLON[0] - (s[0] - degerMm) / Math.max(1e-6, (s[3] - s[0]) / 1.8808)
  else if (degerMm >= s[6]) z = Z_KOLON[6] + (degerMm - s[6]) / Math.max(1e-6, (s[6] - s[3]) / 1.8808)
  else {
    let i = 0; while (i < 6 && degerMm > s[i + 1]) i++
    const f = (degerMm - s[i]) / Math.max(1e-6, s[i + 1] - s[i])
    z = Z_KOLON[i] + (Z_KOLON[i + 1] - Z_KOLON[i]) * f
  }
  const persentil = Math.round(normalCdf(z) * 100)
  const durum = persentil < 10 ? 'dusuk' : persentil > 90 ? 'yuksek' : 'normal'
  return { parametre: param, deger: degerMm, p50: Math.round(s[3] * 10) / 10, persentil: Math.min(99, Math.max(1, persentil)), z: Math.round(z * 100) / 100, durum }
}

/** Hadlock 3-parametre EFW (gram). Girdiler mm → cm. */
export function hadlockEfw(hcMm: number, acMm: number, flMm: number): number | null {
  const hc = hcMm / 10, ac = acMm / 10, fl = flMm / 10
  if (![hc, ac, fl].every((v) => isFinite(v) && v > 0)) return null
  const log10 = 1.326 - 0.00326 * ac * fl + 0.0107 * hc + 0.0438 * ac + 0.158 * fl
  return Math.round(Math.pow(10, log10))
}

/** Grafik için: 3-50-97 persentil eğrileri (14-40 hafta). */
export function biyometriEgrileri(param: BiyometriParametre) {
  const t = TABLO[param]
  return Object.keys(t).map(Number).sort((a, b) => a - b).map((h) => ({ hafta: h, p3: t[h][0], p10: t[h][2], p50: t[h][3], p90: t[h][4], p97: t[h][6] }))
}
