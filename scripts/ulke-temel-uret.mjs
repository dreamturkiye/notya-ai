#!/usr/bin/env node
/**
 * NOTYA-ULKE-PORTAL-01 — GENERATES THE BASELINE of a new, empty country database:
 * lib/db/ulke/000_yeni_ulke_veritabani.sql.
 *
 * ONE DATABASE PER COUNTRY (Kaan, 2026-10-09: "We had issues with common databases before. Keep seperation between
 * the two and any other future country versions"). A new country gets its own database, and that database is created
 * by running ONE file once. This script writes that file from the country migrations, in the order of
 * lib/db/ulke/gocler.json, so the baseline can never say anything the migrations do not say:
 *
 *   - the ledger table (lib/db/ulke/defter.sql) comes first;
 *   - then the body of every country migration, exactly as written, with three things taken out:
 *       its own `begin; … commit;` (the baseline is ONE transaction: applied completely or not at all),
 *       every `drop … if exists` statement (they exist only so that a migration can be run twice; on an empty
 *       database there is nothing to drop, and a tool that applies SQL by hand refuses them),
 *       every comment line outside a function body (the commented source is the migration file itself);
 *   - a guard in front: the file refuses to run on a database whose `public` schema already holds a table, so it
 *     cannot be run twice, and cannot be run on a database that is already in use by anybody.
 *
 *   node scripts/ulke-temel-uret.mjs              writes the file
 *   node scripts/ulke-temel-uret.mjs --kontrol    writes nothing; exit code 1 if the file is not what would be written
 *
 * It reads and writes files of this repository only. It connects to nothing.
 * That the result gives EXACTLY the schema the migrations give is proven on a throwaway local PostgreSQL by
 * scripts/ulke-temel-kaniti.mjs; that the file is up to date is a test (lib/ulke/ulkeTemel.test.ts).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const KOK_VARSAYILAN = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The list every script and test reads: which files are country migrations, and in which order. */
export function gocListesi(kok = KOK_VARSAYILAN) {
  const l = JSON.parse(readFileSync(join(kok, 'lib/db/ulke/gocler.json'), 'utf8'))
  return { defter: l.defter, temel: l.temel, dizin: l.dizin, gocler: [...l.gocler], elleUygulanan: [...l.elleUygulanan] }
}

const DOLAR = /\$\$/g

/**
 * Lines of SQL with the comment lines and the `drop … if exists` statements taken out — but only OUTSIDE a
 * dollar-quoted body: the text of a function is kept byte for byte, comments included (it is part of the schema).
 */
export function sadelestir(sql, { dropAt = true, yorumAt = true } = {}) {
  const cikti = []
  let govdede = false
  for (const satir of sql.split('\n')) {
    const basta = govdede
    if ((satir.match(DOLAR)?.length ?? 0) % 2 === 1) govdede = !govdede
    if (!basta) {
      if (yorumAt && /^\s*--/.test(satir)) continue
      if (dropAt && /^\s*drop\s+\w+\s+if\s+exists\b[^;]*;\s*$/i.test(satir)) continue
    }
    cikti.push(satir.replace(/\s+$/, ''))
  }
  return cikti.join('\n').replace(/\n{3,}/g, '\n\n').trim()
}

/** The statements of one migration: what lies between its `begin; set local lock_timeout …;` and its `commit;`. */
export function gocGovdesi(sql, ad) {
  const m = /^begin;\s*\nset local lock_timeout = '4s';\s*\n([\s\S]*?)\ncommit;\s*$/m.exec(sql)
  if (!m) throw new Error(`${ad}: not one transaction of the shape "begin; set local lock_timeout = '4s'; … commit;"`)
  return m[1]
}

/** A migration exactly as somebody applies it by hand through a tool that refuses `drop … if exists`: those lines left out, nothing else changed. */
export const dropsuz = (sql) => sadelestir(sql, { dropAt: true, yorumAt: false })

export function temelUret(kok = KOK_VARSAYILAN) {
  const l = gocListesi(kok)
  const ilk = l.gocler[0].slice(0, 3), son = l.gocler[l.gocler.length - 1].slice(0, 3)
  const parcalar = [
    `-- BASELINE OF A NEW, EMPTY COUNTRY DATABASE. Migrations ${ilk} to ${son}, as one file.
--
-- GENERATED by scripts/ulke-temel-uret.mjs from lib/db/ulke/gocler.json. DO NOT EDIT BY HAND: change or add a
-- migration, add it to that list, and run the script again. The commented source of every statement below is the
-- migration file named above it.
--
-- WHAT IT IS FOR. One database per country. A new country's own database is created empty, and this file is run on
-- it ONCE. It creates every table, rule, function and the recordings bucket a country build needs, and the ledger
-- that records which migrations the database holds (${ilk} to ${son}, one row each). Migrations written after this
-- file was generated are then run one by one, as files.
--
-- WHERE IT MAY RUN. On a database whose \`public\` schema holds no table at all. It checks that itself, first, and
-- refuses with an error otherwise: it cannot be run twice, and it cannot be run on a database that is in use.
-- It is one transaction: it is applied completely or not at all.
--
-- It expects what every new project of the database provider brings: the roles anon, authenticated and service_role,
-- the sign-in tables and functions (auth.users, auth.uid(), auth.jwt()) and the storage tables (storage.buckets,
-- storage.objects, storage.foldername()).

begin;
set local lock_timeout = '4s';

do $$
declare n integer;
begin
  select count(*) into n
    from pg_class c join pg_namespace s on s.oid = c.relnamespace
   where s.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm', 'f');
  if n > 0 then
    raise exception 'baseline refused: the public schema of this database already holds % table(s). This file is for a NEW, EMPTY country database and is run once.', n;
  end if;
end $$;`,
    `-- ── the ledger (${l.defter}) ──\n${sadelestir(readFileSync(join(kok, l.defter), 'utf8'))}`,
    ...l.gocler.map((ad) => `-- ── ${ad} ──\n${sadelestir(gocGovdesi(readFileSync(join(kok, l.dizin, ad), 'utf8'), ad))}`),
    'commit;',
  ]
  const metin = `${parcalar.join('\n\n')}\n`
  // What the file promises about itself, checked on the text before it is written.
  const govdesiz = metin.split('\n').filter((s) => !/^\s*--/.test(s)).join('\n')
  if (/\bdrop\b/i.test(govdesiz)) throw new Error('the baseline would hold a "drop" statement')
  if ((govdesiz.match(/^begin;$/gm) ?? []).length !== 1 || (govdesiz.match(/^commit;$/gm) ?? []).length !== 1) throw new Error('the baseline must be exactly one transaction')
  return metin
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const l = gocListesi()
  const metin = temelUret()
  const yol = join(KOK_VARSAYILAN, l.temel)
  if (process.argv.includes('--kontrol')) {
    let mevcut = ''
    try { mevcut = readFileSync(yol, 'utf8') } catch { /* missing = stale */ }
    if (mevcut !== metin) { console.error(`${l.temel} is not what the migrations give. Run: node scripts/ulke-temel-uret.mjs`); process.exit(1) }
    console.log(`${l.temel} is up to date (${l.gocler.length} migrations, ${metin.split('\n').length} lines).`)
  } else {
    writeFileSync(yol, metin)
    console.log(`wrote ${l.temel}: ${l.gocler.length} migrations (${l.gocler[0]} … ${l.gocler[l.gocler.length - 1]}), ${metin.split('\n').length} lines.`)
  }
}
